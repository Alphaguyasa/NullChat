package et.alpha.nchat.mesh.crypto

import android.content.Context
import android.util.Log
import com.google.crypto.tink.Aead
import com.google.crypto.tink.KeyTemplates
import com.google.crypto.tink.aead.AeadConfig
import com.google.crypto.tink.integration.android.AndroidKeysetManager
import com.google.crypto.tink.subtle.Ed25519Sign
import com.google.crypto.tink.subtle.Ed25519Verify
import com.google.crypto.tink.subtle.X25519
import et.alpha.nchat.data.db.hexIdToBytes
import et.alpha.nchat.data.db.toHexId
import et.alpha.nchat.mesh.protocol.Packet
import et.alpha.nchat.mesh.protocol.peerIdFor
import java.security.GeneralSecurityException

/**
 * This device's long-term key material.
 *
 * Holds an Ed25519 signing keypair and an X25519 key-agreement keypair,
 * generated once on first launch and kept for the life of the install. The
 * Ed25519 public key *is* this device's identity: `peerId` is the first 8 bytes
 * of its SHA-256, so losing the key means becoming a different device.
 *
 * ## Why the keys are not themselves in the Keystore
 *
 * Android Keystore cannot hold Ed25519 or X25519. Its provider exposes only the
 * NIST curves — BoringSSL does not offer Curve25519 through AndroidKeyStore —
 * and Keystore-native Ed25519 needs API 33 against this app's minSdk of 26.
 *
 * So the keys are generated by Tink in software and *sealed*: a 64-byte blob of
 * raw private key material, encrypted with a Tink AEAD whose own keyset is
 * wrapped by an AES-GCM master key that genuinely lives in the Keystore. The
 * private bytes exist in app memory while the process runs, which is weaker than
 * a hardware-backed key and is the price of using the curves the wire format
 * specifies.
 *
 * Raw key bytes rather than a Tink keyset for the identity keys, because the
 * public key has to travel: it goes in an ANNOUNCE payload and a QR code as 32
 * plain bytes, and peerId is a hash of exactly those bytes.
 */
class KeyManager(
    private val context: Context,
) {

    private val preferences by lazy {
        context.applicationContext.getSharedPreferences(PREFERENCES, Context.MODE_PRIVATE)
    }

    private val material: KeyMaterial by lazy { loadOrCreate() }

    /** Ed25519 public key, 32 bytes. Safe to publish; this is what a QR encodes. */
    val signingPublicKey: ByteArray get() = material.signingPublic.copyOf()

    /** X25519 public key, 32 bytes. Announced so peers can seal direct messages to us; see SessionCipher. */
    val agreementPublicKey: ByteArray get() = material.agreementPublic.copyOf()

    /** This device's 8-byte mesh id, committed to [signingPublicKey]. */
    val peerId: ByteArray by lazy { peerIdFor(material.signingPublic) }

    /** Signs [bytes] — in practice always `PacketCodec.signedBytes(packet)`. */
    fun sign(bytes: ByteArray): ByteArray = Ed25519Sign(material.signingPrivate).sign(bytes)

    /**
     * Computes the shared secret with [peerAgreementPublicKey].
     *
     * Unused in stage 1; the X25519 keypair is generated now so that turning on
     * encryption later does not change this device's identity or force a
     * re-pair.
     */
    fun sharedSecretWith(peerAgreementPublicKey: ByteArray): ByteArray =
        X25519.computeSharedSecret(material.agreementPrivate, peerAgreementPublicKey)

    private fun loadOrCreate(): KeyMaterial {
        val aead = masterAead()

        preferences.getString(KEY_SEALED_MATERIAL, null)?.let { stored ->
            // A keyset that will not open is recoverable by starting over; a
            // service that throws on every start is not. This happens for real:
            // a Keystore master key can be invalidated by a lock-screen change,
            // and a cloud-restored backup arrives with no matching Keystore key
            // at all.
            runCatching { KeyMaterial.unseal(aead.decrypt(stored.hexIdToBytes(), ASSOCIATED_DATA)) }
                .onFailure { Log.w(TAG, "sealed key material unreadable, generating a new identity") }
                .getOrNull()
                ?.let { return it }
        }

        val generated = KeyMaterial.generate()
        preferences.edit()
            .putString(KEY_SEALED_MATERIAL, aead.encrypt(generated.seal(), ASSOCIATED_DATA).toHexId())
            .apply()
        Log.i(TAG, "generated a new identity as ${Packet.tag(peerIdFor(generated.signingPublic))}")
        return generated
    }

    /**
     * The Keystore-backed AEAD that seals the key material.
     *
     * `AndroidKeysetManager` generates the keyset on first use and encrypts it
     * with a Keystore key named by [MASTER_KEY_URI]. Only its `rotate()` is
     * deprecated; this construction is current.
     */
    private fun masterAead(): Aead {
        AeadConfig.register()
        return AndroidKeysetManager.Builder()
            .withSharedPref(context.applicationContext, KEYSET_NAME, PREFERENCES)
            .withKeyTemplate(KeyTemplates.get("AES256_GCM"))
            .withMasterKeyUri(MASTER_KEY_URI)
            .build()
            .keysetHandle
            .getPrimitive(Aead::class.java)
    }

    private companion object {
        const val TAG = "KeyManager"

        const val PREFERENCES = "mesh_keys"
        const val KEYSET_NAME = "nchat_master_keyset"
        const val KEY_SEALED_MATERIAL = "sealed_identity"
        const val MASTER_KEY_URI = "android-keystore://nchat_master"

        /**
         * Binds the sealed blob to its purpose, so a ciphertext lifted from
         * these preferences cannot be replayed as some other AEAD input.
         */
        val ASSOCIATED_DATA = "nchat.identity.v1".toByteArray()
    }
}

/**
 * The raw private and public halves of both keypairs.
 *
 * Sealed as `ed25519Private || x25519Private`; the public halves are derived on
 * load rather than stored, so the blob cannot become internally inconsistent.
 */
private class KeyMaterial(
    val signingPrivate: ByteArray,
    val signingPublic: ByteArray,
    val agreementPrivate: ByteArray,
    val agreementPublic: ByteArray,
) {

    fun seal(): ByteArray = signingPrivate + agreementPrivate

    companion object {
        const val PRIVATE_KEY_SIZE = 32

        fun generate(): KeyMaterial {
            val signing = Ed25519Sign.KeyPair.newKeyPair()
            val agreementPrivate = X25519.generatePrivateKey()
            return KeyMaterial(
                signingPrivate = signing.privateKey,
                signingPublic = signing.publicKey,
                agreementPrivate = agreementPrivate,
                agreementPublic = X25519.publicFromPrivate(agreementPrivate),
            )
        }

        @Throws(GeneralSecurityException::class)
        fun unseal(blob: ByteArray): KeyMaterial {
            require(blob.size == PRIVATE_KEY_SIZE * 2) {
                "sealed material must be ${PRIVATE_KEY_SIZE * 2} bytes, was ${blob.size}"
            }
            val signingPrivate = blob.copyOfRange(0, PRIVATE_KEY_SIZE)
            val agreementPrivate = blob.copyOfRange(PRIVATE_KEY_SIZE, blob.size)
            return KeyMaterial(
                signingPrivate = signingPrivate,
                signingPublic = Ed25519Sign.KeyPair.newKeyPairFromSeed(signingPrivate).publicKey,
                agreementPrivate = agreementPrivate,
                agreementPublic = X25519.publicFromPrivate(agreementPrivate),
            )
        }
    }
}

/** Verifies an Ed25519 signature against a raw 32-byte public key. */
internal fun verifyEd25519(
    publicKey: ByteArray,
    signedBytes: ByteArray,
    signature: ByteArray,
): Boolean = runCatching { Ed25519Verify(publicKey).verify(signature, signedBytes) }.isSuccess
